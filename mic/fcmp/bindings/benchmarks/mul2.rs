fn main() {
    println!("Helios / Selene Scalar Multiplication Benchmark");

    // ====================== HELIOS BENCHMARK ======================
    let GH = HeliosPoint::generator();   // Base point G for Helios

    let scalars_helios: Vec<HelioseleneField> = HELIOS_SCALARS_HEX
        .iter()
        .map(|hex_str| {
            // Exact style that works, as you showed
            let xhbi = U256::from_be_hex(hex_str);
            let xh = HelioseleneField::from_repr(xhbi.to_le_bytes()).unwrap();
            xh
        })
        .collect();

    let start = Instant::now();

    let num_ops = 100;
    for i in 0..num_ops {
        for &scalar in &scalars_helios {
            let _ = GH * scalar;
        }
    }

    let duration_helios = start.elapsed();
    println!("Helios: {:.4} seconds", duration_helios.as_secs_f64());
    println!("Average per mul   : {:.2} ms",
        duration_helios
        .div_f64(num_ops as f64)
        .div_f64(scalars_helios.len() as f64)
        .as_secs_f64() * 1000.0
);


    // ====================== HELIOS CORRECTNESS ======================
    let mut P;
    let mut bex;
    let mut bey;
    let mut i = 0;

    for &scalar in &scalars_helios {
        P = GH * scalar;
        bex = (P.x * P.z.invert().unwrap()).to_repr();
        bex.reverse();
        // println!("x = {:?} ", hex::encode(bex));
        bey = (P.y * P.z.invert().unwrap()).to_repr();
        bey.reverse();
        // println!("y = {:?} ", hex::encode(bey));

        assert_eq!(hex::encode(bex), HELIOS_RESULT[i].0);
        assert_eq!(hex::encode(bey), HELIOS_RESULT[i].1);
        i=i+1;
    }

    // ====================== SELENE BENCHMARK ======================
    let GS = SelenePoint::generator();   // Base point G for Selene

    let scalars_selene: Vec<Field25519> = SELENE_SCALARS_HEX
        .iter()
        .map(|hex_str| {
            // Exact style you requested
            let u256 = U256::from_be_hex(hex_str);
            let xs = Field25519::from_u256(&u256);
            xs
        })
        .collect();

    let start = Instant::now();

    let num_ops = 100;
    for i in 0..num_ops {
        for &scalar in &scalars_selene {
            GS * scalar;
        }
    }

    let duration_selene = start.elapsed();
    println!("Selene: {:.4} seconds", duration_selene.as_secs_f64());
    println!("Average per mul   : {:.2} ms",
        duration_selene
        .div_f64(num_ops as f64)
        .div_f64(scalars_selene.len() as f64)
        .as_secs_f64() * 1000.0
);

    // ====================== SELENE CORRECTNESS ======================

    let mut PS;
    i = 0;
    for &scalar in &scalars_selene {
        PS = GS * scalar;
        bex = (PS.x * PS.z.invert().unwrap()).to_repr();
        bex.reverse();
        // println!("x = {:?} ", hex::encode(bex));
        bey = (PS.y * PS.z.invert().unwrap()).to_repr();
        bey.reverse();
        // println!("y = {:?} ", hex::encode(bey));

        assert_eq!(hex::encode(bex), SELENE_RESULT[i].0);
        assert_eq!(hex::encode(bey), SELENE_RESULT[i].1);
        i=i+1;
    }


    println!("\nBenchmark finished.");
}
